"""
simulation.py

Kinematic C. elegans-like worm simulation (no axes, 2D container).
The worm is represented as a sinusoidal midline whose amplitude and
heading change over time, giving a noisy, slithering motion.

Run with:
    python simulation.py

If you need dependencies:
    python -m pip install numpy matplotlib
"""

# -----------------------------
# Global parameters
# -----------------------------

FPS = 30                    # frames per second (higher FPS, smoother motion)
DT = 1.0 / FPS              # time step in seconds

N_SEG = 40                  # number of points along the body (short, stubby worm)
BODY_LENGTH = 1.0           # total body length (arbitrary units, stubby worm)
WAVE_K = 0.25               # at most one gentle bend along the body
BASE_AMP = 0.05             # very small amplitude (barely undulating)
AMP_NOISE_GAIN = 0.10       # small variability
AMP_NOISE_DECAY = 0.9997    # extremely slow drift in bending amplitude

CPG_FREQ = 0.22             # slower, more biological undulation

# Propulsion in a resistive fluid: forward speed is generated by
# body undulations and scaled by this coefficient.
# Slightly higher coefficient and minimum speed effectively reduce
# "fluid resistance" so the worm translates faster.
FLUID_PROP_COEFF = 3.0      # stronger propulsion in fluid
MIN_FORWARD_SPEED = 0.025   # slightly higher forward floor

# Center-of-mass / head motion
MEAN_SPEED = 0.05           # slow crawling speed
SPEED_NOISE_GAIN = 0.18     # reduced variability
HEADING_DIFFUSION = np.deg2rad(8.0)   # small random drift of desired heading
TURN_RATE_LIMIT = np.deg2rad(70.0)    # max turn rate of actual heading (deg/s)
WALL_DETECT_MARGIN = 0.05             # early wall detection distance
WALL_AVOID_TIME = 1.0                 # seconds to keep steering away after a hit

# Curvature dynamics (controls how smoothly the head path bends)
CURVATURE_DECAY = 0.985                 # previous curvature persists longer
CURVATURE_NOISE_GAIN = np.deg2rad(2.0)  # smaller random curvature fluctuations
WALL_TURN_RATE = np.deg2rad(55.0)       # target curvature magnitude when avoiding a wall (rad/s)

# Container bounds (a simple box the worm lives in)
X_MIN, X_MAX = -2.5, 2.5
Y_MIN, Y_MAX = -1.5, 1.5

# Total duration of Brian2 VNC simulation (seconds of motor drive)
NETWORK_DURATION = 60.0

# Path to connectivity Excel file containing the real C. elegans connectivity.
# This should be the original spreadsheet in the project directory.
CONNECTIVITY_FILE = "CElegansNeuronConnections.xls"

# Placeholders for Brian2-generated motor drive (filled later)
network_A = None          # amplitude over time (from spikes)
network_curv = None       # curvature drive over time (from spikes)
network_len = 0           # number of samples
network_idx = 0           # current index into network arrays

# -----------------------------
# State variables
# -----------------------------

# Parameter along the body from head (0) to tail (1)
s = np.linspace(0.0, 1.0, N_SEG)

# Phase of the central pattern generator
phase = 0.0

# Smoothed random variable controlling amplitude variations
amp_noise_state = 0.0

# Heading angle of the worm (radians, 0 = positive x direction)
heading = 0.0

# Desired heading that the worm steers toward (for smooth turning)
target_heading = 0.0

# Timer indicating recent wall contact; during this time the worm prefers
# to keep steering away from the wall.
wall_avoid_timer = 0.0

# Curvature of the path (roughly, d(heading)/dt); used to ensure that
# the head direction changes smoothly over time (no teleporting angles).
curvature = 0.0

# Bias on curvature, mainly used for wall avoidance (steering away).
curvature_bias = 0.0

# Head position (x, y)
head_pos = np.array([0.0, 0.0], dtype=float)

# History of whole-body shapes so that the tail can trail behind
# the head with a realistic time lag.
MAX_HISTORY = N_SEG           # one frame of lag per segment
shape_history = np.zeros((MAX_HISTORY, N_SEG, 2), dtype=float)
history_idx = 0
history_filled = 0


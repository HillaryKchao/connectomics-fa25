head_marker, = ax.plot([], [], marker='o', markersize=6, color="#ffffff", zorder=5)
ax.set_xlim(X_MIN, X_MAX)
ax.set_ylim(Y_MIN, Y_MAX)
ax.set_aspect("equal")

# Hide all axes / ticks so it doesn't look like a graph
ax.set_xticks([])
ax.set_yticks([])
for spine in ax.spines.values():
    spine.set_visible(False)

fig.tight_layout()
fig.canvas.manager.set_window_title("C. elegans-like worm slithering")

def init():
    line.set_data([], [])
    head_marker.set_data([], [])
    return line, head_marker

def animate(frame):
    # Update the faux brain state and get new amplitude
    A = update_brain(DT)

    # Compute worm midline in world coordinates
    x, y = body_midline(A)
    line.set_data(x, y)

    # Place the head marker at the head (s = 0 -> index 0)
    if len(x) > 0:
        head_marker.set_data([x[0]], [y[0]])
    else:
        head_marker.set_data([], [])

    return line, head_marker

anim = FuncAnimation(
    fig,
    animate,
    init_func=init,
    frames=None,        # animate indefinitely
    interval=1000.0*DT, # milliseconds between frames (~30 FPS)
    blit=True
)

if __name__ == "__main__":
    plt.show()
